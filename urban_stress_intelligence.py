def rebuild_city_pm25(raw_df):
    df = raw_df.copy()

    # Make sure types are correct
    df["date"] = pd.to_datetime(df["date"])
    df["pm25"] = pd.to_numeric(df["pm25"], errors="coerce")

    # One city-day = median across available sensors
    daily = (
        df
        .groupby(["city", "date"], as_index=False)
        .agg(
            pm25=("pm25", "median"),
            sensor_count=("sensor_id", "nunique")
        )
    )

    daily["coverage_status"] = np.where(
        daily["sensor_count"] >= 2,
        "Multi-sensor",
        "Single-sensor"
    )

    daily["data_quality_score"] = np.where(
        daily["sensor_count"] >= 2,
        100,
        80
    )

    return daily


