import time

def get_pm25_data(
    city_name,
    latitude,
    longitude,
    start_date,
    end_date,
    api_key,
    radius=10000
):

    headers = {
        "X-API-Key": api_key
    }

    # ------------------------------------------------
    # STEP 1: Find nearby monitoring locations
    # ------------------------------------------------

    locations_url = "https://api.openaq.org/v3/locations"

    location_params = {
        "coordinates": f"{latitude},{longitude}",
        "radius": radius,
        "limit": 100
    }

    response = requests.get(
        locations_url,
        headers=headers,
        params=location_params,
        timeout=30
    )

    response.raise_for_status()
    time.sleep(1) # Delay to respect rate limits

    locations_data = response.json()

    locations = locations_data.get("results", [])

    if not locations:
        print(f"{city_name}: No monitoring locations found.")
        return pd.DataFrame()

    # ------------------------------------------------
    # STEP 2: Find PM2.5 sensors
    # ------------------------------------------------

    sensors = []

    for location in locations:

        location_id = location["id"]
        location_name = location.get("name")

        sensors_url = (
            f"https://api.openaq.org/v3/"
            f"locations/{location_id}/sensors"
        )

        sensor_response = requests.get(
            sensors_url,
            headers=headers,
            timeout=30
        )
        time.sleep(1) # Delay to respect rate limits

        if sensor_response.status_code != 200:
            continue

        sensor_results = sensor_response.json().get(
            "results",
            []
        )

        for sensor in sensor_results:

            parameter = sensor.get("parameter", {})

            if parameter.get("name") == "pm25":

                first_date = sensor.get("datetimeFirst")
                last_date = sensor.get("datetimeLast")

                # Extract local timestamps
                if isinstance(first_date, dict):
                    first_date = first_date.get("local")

                if isinstance(last_date, dict):
                    last_date = last_date.get("local")

                sensors.append({
                    "sensor_id": sensor["id"],
                    "location_name": location_name,
                    "first_date": first_date,
                    "last_date": last_date
                })

    sensor_df = pd.DataFrame(sensors)

    if sensor_df.empty:
        print(f"{city_name}: No PM2.5 sensors found.")
        return pd.DataFrame()

    # ------------------------------------------------
    # STEP 3: Convert dates
    # ------------------------------------------------

    sensor_df["first_date"] = pd.to_datetime(
        sensor_df["first_date"],
        utc=True,
        errors="coerce"
    ).dt.date

    sensor_df["last_date"] = pd.to_datetime(
        sensor_df["last_date"],
        utc=True,
        errors="coerce"
    ).dt.date

    target_start = pd.Timestamp(start_date).date()
    target_end = pd.Timestamp(end_date).date()

    # ------------------------------------------------
    # STEP 4: Find sensors covering target period
    # ------------------------------------------------

    usable_sensors = sensor_df[
        (sensor_df["first_date"] <= target_end) &
        (sensor_df["last_date"] >= target_start)
    ].copy()

    if usable_sensors.empty:
        print(
            f"{city_name}: No PM2.5 sensors "
            f"cover the requested period."
        )
        return pd.DataFrame()

    print(
        f"{city_name}: "
        f"{len(usable_sensors)} usable PM2.5 sensor(s)"
    )

    # ------------------------------------------------
    # STEP 5: Download daily data
    # ------------------------------------------------

    all_data = []

    for _, sensor in usable_sensors.iterrows():

        sensor_id = sensor["sensor_id"]

        days_url = (
            f"https://api.openaq.org/v3/"
            f"sensors/{sensor_id}/days"
        )

        params = {
            "date_from": start_date,
            "date_to": end_date,
            "limit": 1000,
            "page": 1
        }

        data_response = requests.get(
            days_url,
            headers=headers,
            params=params,
            timeout=30
        )
        time.sleep(1) # Delay to respect rate limits

        if data_response.status_code != 200:
            continue

        data = data_response.json()

        results = data.get("results", [])

        if not results:
            continue

        df = pd.json_normalize(results)

        # ------------------------------------------------
        # STEP 6: Extract required fields
        # ------------------------------------------------

        df["datetime"] = pd.to_datetime(
            df["period.datetimeFrom.local"],
            utc=True,
            errors="coerce"
        )

        df["date"] = df["datetime"].dt.date

        df["pm25"] = pd.to_numeric(
            df["value"],
            errors="coerce"
        )

        df["city"] = city_name

        df["sensor_id"] = sensor_id

        df["location_name"] = sensor["location_name"]

        df = df[
            [
                "date",
                "city",
                "pm25",
                "sensor_id",
                "location_name"
            ]
        ]

        all_data.append(df)

    # ------------------------------------------------
    # STEP 7: Combine sensors
    # ------------------------------------------------

    if not all_data:
        print(
            f"{city_name}: "
            "No daily PM2.5 data returned."
        )
        return pd.DataFrame()

    final_df = pd.concat(
        all_data,
        ignore_index=True
    )

    final_df["date"] = pd.to_datetime(
        final_df["date"]
    )

    # ------------------------------------------------
    # STEP 8: Remove exact duplicates
    # ------------------------------------------------

    final_df = final_df.drop_duplicates(
        subset=[
            "date",
            "sensor_id"
        ]
    )

    final_df = final_df.sort_values(
        ["date", "sensor_id"]
    ).reset_index(drop=True)

    return final_df

