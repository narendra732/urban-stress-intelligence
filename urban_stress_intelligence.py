def get_weather(city_name, latitude, longitude, start, end):

    # Create geographic point
    point = ms.Point(latitude, longitude)

    # Find nearby weather stations
    stations = ms.stations.nearby(
        point,
        limit=4
    )

    # Get daily observations
    data = ms.daily(
        stations,
        start,
        end
    )

    # Interpolate station observations to city point
    weather = ms.interpolate(
        data,
        point
    ).fetch()

    # Convert index to column
    weather = weather.reset_index()

    # Rename date column
    weather = weather.rename(
        columns={"time": "date"}
    )

    # Add city
    weather["city"] = city_name

    # Keep required columns
    weather = weather[
        [
            "date",
            "city",
            "temp",
            "tmin",
            "tmax",
            "rhum",
            "prcp",
            "wspd"
        ]
    ]

    return weather

