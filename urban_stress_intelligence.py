def calculate_coverage(df, start_date, end_date):

    expected_days = pd.date_range(
        start_date,
        end_date,
        freq="D"
    )

    available_days = (
        df["date"]
        .isin(expected_days)
        .sum()
    )

    total_days = len(expected_days)

    coverage = (
        available_days /
        total_days *
        100
    )

    return available_days, total_days, coverage

